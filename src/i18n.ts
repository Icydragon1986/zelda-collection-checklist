const STORAGE_KEY = "triforce-checklist-language";

function getInitialLanguage(): Language {
  const stored = localStorage.getItem(STORAGE_KEY);
  return stored === "en" ? "en" : "fr";
}

export function translate(language: Language, key: string, values: Record<string, string | number> = {}): string {
  const template = translations[language][key] ?? translations.fr[key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values[name] ?? `{{${name}}}`));
}

interface LanguageState {
  language: Language;
  setLanguage: (language: Language) => void;
}

export const useLanguage = create<LanguageState>((set) => ({
  language: getInitialLanguage(),
  setLanguage: (language) => {
    localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
    set({ language });
  },
}));

document.documentElement.lang = useLanguage.getState().language;

export function useI18n() {
  const language = useLanguage((state) => state.language);
  const setLanguage = useLanguage((state) => state.setLanguage);
  return {
    language,
    setLanguage,
    t: (key: string, values?: Record<string, string | number>) => translate(language, key, values),
  };
}

export const regionLabel = (region: Region, language: Language) => translate(language, `regions.${region}`);
export const categoryLabel = (category: GameCategory, language: Language) => translate(language, `categories.${category}`);
export const seriesLabel = (series: AmiiboSeries, language: Language) => translate(language, `series.${series}`) === `series.${series}` ? series : translate(language, `series.${series}`);
